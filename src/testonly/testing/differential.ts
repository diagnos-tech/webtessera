// Shared machinery of the differential suites, which replay the corpora in
// fixtures/data/differential_*.json (generated by fixtures/gen/differential*.go from
// the real Go code) and require the port to reach Go's verdict on every record.
// See docs/compatibility.md ("Differential tests") and
// docs/decisions/0215-differential-corpora.md.
//
// A record may differ from Go only under a named entry of DIVERGENCES, each of which
// cites the ADR that decided it and states the exact behaviour the port must show
// instead. A suite that meets a difference no entry covers reports it as a mismatch;
// a suite that applies an entry counts it, so the report shows how often each
// documented divergence occurs and a divergence cannot spread silently.

import { expect } from "vitest";

/** A DivergenceRule is one documented, ADR-backed way the port may differ from Go. */
export interface DivergenceRule {
	/** adrs are the decision records (docs/decisions/NNNN-*.md) that decided it. */
	readonly adrs: readonly string[];
	/** rule says what the port does instead of what Go does, precisely enough to assert. */
	readonly rule: string;
}

