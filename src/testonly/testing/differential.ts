/** DivergenceName names an entry of {@link DIVERGENCES}. */
export type DivergenceName = keyof typeof DIVERGENCES;

/** maxReported is how many mismatches a failing report spells out. */
const maxReported = 25;

/**
 * DifferentialReport collects the outcome of replaying one corpus: how many records were
 * checked, every mismatch (the first few spelled out in full, with the input), and how
 * often each documented divergence was applied.
 */
export class DifferentialReport {
	readonly corpus: string;
	checked = 0;
	mismatchCount = 0;
	readonly mismatches: string[] = [];
	readonly divergences = new Map<DivergenceName, number>();

	constructor(corpus: string) {
		this.corpus = corpus;
	}

	/** record counts one replayed record. */
	record(): void {
		this.checked++;
	}

	/** fail records a mismatch for the record identified by id. */
	fail(id: string, message: string): void {
		this.mismatchCount++;
		if (this.mismatches.length < maxReported) {
			this.mismatches.push(`${id}: ${message}`);
		}
	}

	/**
	 * equal compares one field of a record. Values are compared by their canonical JSON
	 * rendering, with bigints as decimal strings and Uint8Arrays as hex, so that Go's
	 * fixture spelling and the port's values compare directly. Returns whether they match.
	 */
	equal(id: string, field: string, go: unknown, ts: unknown): boolean {
		const g = canonical(go);
		const t = canonical(ts);
		if (g !== t) {
			this.fail(id, `${field}: go=${clip(g)} ts=${clip(t)}`);
			return false;
		}
		return true;
	}

	/** diverge records that the documented divergence name was applied to record id. */
	diverge(name: DivergenceName): void {
		this.divergences.set(name, (this.divergences.get(name) ?? 0) + 1);
	}

	/**
	 * assertClean fails the test unless every record matched Go or a documented divergence,
	 * at least minChecked records were replayed (so a corpus that failed to load cannot
	 * pass vacuously), only the divergences listed in allowed were applied, and each one
	 * listed in required was applied at least once (so the corpus keeps exercising it).
	 */
	assertClean(
		minChecked: number,
		allowed: readonly DivergenceName[] = [],
		required: readonly DivergenceName[] = [],
	): void {
		for (const name of this.divergences.keys()) {
			if (!allowed.includes(name)) {
				this.fail("(report)", `divergence ${name} applied, but this corpus does not allow it`);
			}
		}
		for (const name of required) {
			if ((this.divergences.get(name) ?? 0) === 0) {
				this.fail("(report)", `divergence ${name} was never applied; the corpus no longer exercises it`);
			}
		}
		const summary = this.summary();
		expect(this.checked, `${this.corpus}: too few records replayed\n${summary}`).toBeGreaterThanOrEqual(minChecked);
		expect(this.mismatchCount, summary).toBe(0);
	}

	/** summary renders the report for a failure message. */
	summary(): string {
		const div = [...this.divergences].map(([k, v]) => `${k}=${v}`).join(", ") || "none";
		const lines = [
			`${this.corpus}: ${this.checked} records, ${this.mismatchCount} mismatches, divergences: ${div}`,
			...this.mismatches,
		];
		if (this.mismatchCount > this.mismatches.length) {
			lines.push(`... and ${this.mismatchCount - this.mismatches.length} more`);
		}
		return lines.join("\n");
	}
}

/** Outcome is the result of calling a function that may throw. */
export type Outcome<T> = { readonly ok: true; readonly value: T } | { readonly ok: false; readonly error: unknown };

/** attempt runs f and captures its result or the value it threw. */
export function attempt<T>(f: () => T): Outcome<T> {
	try {
		return { ok: true, value: f() };
	} catch (error) {
		return { ok: false, error };
	}
}

/** attemptAsync is {@link attempt} for an async function. */
export async function attemptAsync<T>(f: () => Promise<T>): Promise<Outcome<T>> {
	try {
		return { ok: true, value: await f() };
	} catch (error) {
		return { ok: false, error };
	}
}

/** messageOf renders a thrown value the way Go's err.Error() reads. */
export function messageOf(e: unknown): string {
	return e instanceof Error ? e.message : String(e);
}

/**
 * sameModuloInvalidUTF8 reports whether a Go error text and the port's agree once every
 * run of invalid-byte spellings is collapsed: Go's `\xNN` escapes and a literal U+FFFD on
 * one side, the port's `\ufffd` escapes and literal U+FFFD on the other. This is the
 * comparison the "invalid-utf8-text" divergence permits.
 */
export function sameModuloInvalidUTF8(go: string, ts: string): boolean {
	const g = go.replace(/(?:\\x[89a-f][0-9a-f]|\ufffd)+/g, "\u0000");
	const t = ts.replace(/(?:\\ufffd|\ufffd)+/g, "\u0000");
	return g === t;
}

/**
 * sameModuloQuoteBound reports whether the port's error text is Go's with one quoted
 * strconv input cut at 64 code points and marked "...", the "numerror-quote-bound"
 * divergence: ts must read `<before>parsing "<prefix>"...<after>` where Go reads
 * `<before>parsing "<prefix><more>"<after>`.
 */
export function sameModuloQuoteBound(go: string, ts: string): boolean {
	const m = /^(.*parsing )("(?:[^"\\]|\\.)*")\.\.\.(.*)$/s.exec(ts);
	if (m === null) {
		return false;
	}
	const [, before, quoted, after] = m as unknown as [string, string, string, string];
	const prefix = quoted.slice(0, -1);
	return (
		go.startsWith(before + prefix) &&
		go.endsWith(`"${after}`) &&
		go.length > before.length + quoted.length + after.length
	);
}

const hexDigits = "0123456789abcdef";

function toHexString(b: Uint8Array): string {
	let out = "";
	for (const v of b) {
		out += hexDigits[v >> 4];
		out += hexDigits[v & 0x0f];
	}
	return out;
}

/** canonical renders a value for comparison: bigint as decimal, bytes as hex. */
export function canonical(v: unknown): string {
	return (
		JSON.stringify(v, (_k, x: unknown) => {
			if (typeof x === "bigint") {
				return x.toString();
			}
			if (x instanceof Uint8Array) {
				return toHexString(x);
			}
			return x;
		}) ?? "undefined"
	);
}

function clip(s: string): string {
	return s.length > 300 ? `${s.slice(0, 300)}…` : s;
}
