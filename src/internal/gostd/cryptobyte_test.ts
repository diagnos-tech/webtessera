describe("TestUint8LengthPrefixedSimple", () => {
	it("backfills the length of a single child", () => {
		const b = new cryptobyte.Builder();
		b.addUint8LengthPrefixed((c) => {
			c.addUint8(23);
			c.addUint8(42);
		});
		builderBytesEq(b, 2, 23, 42);

		const base = new cryptobyte.String(b.bytesOrPanic());
		const child = base.readUint8LengthPrefixed();
		if (child === undefined) {
			throw new Error("parsing failed");
		}
		const x = child.readUint8();
		const y = child.readUint8();
		expect(x).toBe(23);
		expect(y).toBe(42);
		expect(base.length).toBe(0);
		expect(child.length).toBe(0);
	});
});

describe("TestUint8LengthPrefixedMulti", () => {
	it("backfills the length of several sibling children", () => {
		const b = new cryptobyte.Builder();
		b.addUint8LengthPrefixed((c) => {
			c.addUint8(23);
			c.addUint8(42);
		});
		b.addUint8(5);
		b.addUint8LengthPrefixed((c) => {
			c.addUint8(123);
			c.addUint8(234);
		});
		builderBytesEq(b, 2, 23, 42, 5, 2, 123, 234);

		const s = new cryptobyte.String(b.bytesOrPanic());
		const first = s.readUint8LengthPrefixed();
		if (first === undefined) {
			throw new Error("parsing failed");
		}
		const u = first.readUint8();
		const v = first.readUint8();
		const w = s.readUint8();
		const second = s.readUint8LengthPrefixed();
		if (second === undefined) {
			throw new Error("parsing failed");
		}
		const x = second.readUint8();
		const y = second.readUint8();
		expect([u, v, w, x, y]).toEqual([23, 42, 5, 123, 234]);
		expect(s.length).toBe(0);
		expect(second.length).toBe(0);
	});
});

describe("TestUint8LengthPrefixedNested", () => {
	it("backfills the lengths of nested children", () => {
		const b = new cryptobyte.Builder();
		b.addUint8LengthPrefixed((c) => {
			c.addUint8(5);
			c.addUint8LengthPrefixed((d) => {
				d.addUint8(23);
				d.addUint8(42);
			});
			c.addUint8(123);
		});
		builderBytesEq(b, 5, 5, 2, 23, 42, 123);

		const base = new cryptobyte.String(b.bytesOrPanic());
		const child1 = base.readUint8LengthPrefixed();
		if (child1 === undefined) {
			throw new Error("parsing base failed");
		}
		const u = child1.readUint8();
		const child2 = child1.readUint8LengthPrefixed();
		if (child2 === undefined) {
			throw new Error("parsing child1 failed");
		}
		const x = child1.readUint8();
		const v = child2.readUint8();
		const w = child2.readUint8();
		expect([u, v, w, x]).toEqual([5, 23, 42, 123]);
		expect(base.length).toBe(0);
		expect(child1.length).toBe(0);
		expect(child2.length).toBe(0);
	});
});

describe("TestPreallocatedBuffer", () => {
	it("appends into the caller's buffer until it is outgrown", () => {
		// Port note: Go builds on `buf[0:0]`, a zero-length slice with room behind it. A
		// Uint8Array has no such thing, so the same state is reached by handing over the
		// array and rolling its length back to zero with unwrite(), as newBuilder's comment
		// describes.
		const buf = new Uint8Array(5);
		const b = cryptobyte.newBuilder(buf);
		b.unwrite(buf.length);
		b.addUint8(1);
		b.addUint8LengthPrefixed((c) => {
			c.addUint8(3);
			c.addUint8(4);
		});
		b.addUint16(1286); // Outgrow buf by one byte.
		expect(Array.from(buf)).toEqual([1, 2, 3, 4, 0]);
		builderBytesEq(b, 1, 2, 3, 4, 5, 6);
	});
});

