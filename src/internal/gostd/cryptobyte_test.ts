import { describe, expect, it } from "vitest";
import * as cryptobyte from "./cryptobyte.ts";

// builderBytesEq asserts that the builder's output is exactly want.
function builderBytesEq(b: cryptobyte.Builder, ...want: number[]): void {
	expect(Array.from(b.bytesOrPanic())).toEqual(want);
}

describe("TestContinuationError", () => {
	it("surfaces a BuildError thrown by a continuation from bytes()", () => {
		const errorStr = "TestContinuationError";
		const b = new cryptobyte.Builder();
		b.addUint8LengthPrefixed((b) => {
			b.addUint8(1);
			throw new cryptobyte.BuildError(new Error(errorStr));
		});

		expect(() => b.bytes()).toThrowError(errorStr);
	});
});

describe("TestContinuationNonError", () => {
	it("rethrows anything that is not a BuildError", () => {
		const b = new cryptobyte.Builder();
		expect(() => {
			b.addUint8LengthPrefixed((b) => {
				b.addUint8(1);
				throw new Error("not a BuildError");
			});
		}).toThrowError("not a BuildError");
	});
});

describe("TestGeneratedPanic", () => {
	it("rethrows a fault raised by the runtime inside a continuation", () => {
		const b = new cryptobyte.Builder();
		expect(() => {
			b.addUint8LengthPrefixed(() => {
				// The equivalent of Go's nil-pointer dereference: a fault generated by the
				// runtime rather than by the builder, which must not be swallowed.
				new Uint8Array(-1);
			});
		}).toThrow(RangeError);
	});
});

describe("TestBytes", () => {
	it("round-trips through AddBytes and ReadBytes", () => {
		const b = new cryptobyte.Builder();
		const v = new TextEncoder().encode("foobarbaz");
		b.addBytes(v.subarray(0, 3));
		b.addBytes(v.subarray(3, 4));
		b.addBytes(v.subarray(4, 9));
		builderBytesEq(b, ...Array.from(v));

		const s = new cryptobyte.String(b.bytesOrPanic());
		for (const w of ["foo", "bar", "baz"]) {
			const got = s.readBytes(3);
			if (got === undefined) {
				throw new Error(`ReadBytes() = false, want true (w = ${w})`);
			}
			expect(Array.from(got)).toEqual(Array.from(new TextEncoder().encode(w)));
		}
		expect(s.length).toBe(0);
	});
});

